def t_lang(key, lang='es'):
    try:
        return TRANSLATIONS.get(lang, TRANSLATIONS['es']).get(key, key)
    except:
        return key

def translate_class_lang(class_name, lang='es'):
    class_map = {
        "Mancha gris": "class_gray_spot",
        "Roña común": "class_common_rust",
        "Tizón del norte": "class_northern_blight",
        "Sano": "class_healthy"
    }
    key = class_map.get(class_name, class_name)
    return t_lang(key, lang)
